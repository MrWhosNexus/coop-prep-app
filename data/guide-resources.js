// data/guide-resources.js
//
// The single source of truth for the datasets guided lessons can name.
//
// A lesson references a dataset by key; something has to hand it the text. That
// map used to live inline in components/Dashboard.js, and every test that
// iterated over all lessons kept its own hardcoded copy containing one entry.
// Registering the six governance labs — which run on hmda-raw.csv — broke nine
// tests across three files at once, all with the same "missing resource"
// error, because each copy had to be found and updated by hand.
//
// One map, imported by the host and by the tests, so adding a dataset is one
// edit and nothing silently keeps an older view of the world.
//
// The CSVs are bundled as JS strings rather than fetched: Chromium refuses
// fetch() on file:// URLs, which is how the packaged Electron build loads the
// app. data/hmda-raw-csv.js and data/hmda-servicing-csv.js are GENERATED by
// scripts/make-governance-data.mjs; do not hand-edit them.

import { HMDA_CSV } from "./hmda-csv.js";
import { HMDA_RAW_CSV } from "./hmda-raw-csv.js";
import { HMDA_SERVICING_CSV } from "./hmda-servicing-csv.js";

/** Resource key -> CSV text. Keys are what a lesson's `resources` names. */
export const GUIDE_RESOURCES = {
  // The clean analytics extract: fair-lending labs, viz labs.
  "hmda-sample.csv": HMDA_CSV,
  // The deliberately dirty intake: profiling, quality rules, completeness,
  // duplicates, standardisation.
  "hmda-raw.csv": HMDA_RAW_CSV,
  // A second system's view of the same book, for reconciliation.
  "hmda-servicing.csv": HMDA_SERVICING_CSV,
};
